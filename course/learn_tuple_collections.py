#Learn Tuple
# Tuples are immutable sequences, typically used to store collections of heterogeneous data. They are similar to lists, but unlike lists, they cannot be changed after their creation. Tuples are defined by enclosing the elements in parentheses `()`.
# The values stored in a tuple can be of any data type, and they can also contain other tuples, lists, or dictionaries. Tuples are often used to represent fixed collections of items, such as coordinates, RGB values, or database records.    

tp=(10,20,30,40,50)

